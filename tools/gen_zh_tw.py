# 观辰 P8-4: builds engine/public/assets/zh-tw-data.json, the Simplified -> Traditional (Taiwan) table used in the browser.
# Same chain as OpenCC "s2twp": [overrides + STPhrases + STCharacters] then [TWPhrases | TWVariantsPhrases | TWVariants],
# longest match first. To keep the download small, only phrases that occur in the site's text (corpus) are kept;
# the character table is kept whole so unseen text still converts character by character.
# Usage: python tools\gen_zh_tw.py   (run again after any copy or page text change; tests/p8_tw_check.mjs reports when it is needed)
# Dictionaries: tools\opencc\ (Apache-2.0, from github.com/BYVoid/OpenCC). The corpus is collected from the repository itself,
# plus tools\zh_tw_corpus_api.txt (text from 300 sample readings, which contains sentences the code assembles at run time).
import glob, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); D = os.path.join(HERE, 'opencc')
OUT = os.path.join(HERE, '..', 'engine', 'public', 'assets', 'zh-tw-data.json')
def load(name):
    d = {}
    for line in open(os.path.join(D, name), encoding='utf-8'):
        if line.startswith('#') or not line.strip(): continue
        k, v = line.rstrip('\n').split('\t'); d[k] = v.split(' ')[0]
    return d
def overrides():
    d = {}
    for line in open(os.path.join(HERE, 'zh_tw_overrides.tsv'), encoding='utf-8'):
        if line.startswith('#') or not line.strip(): continue
        k, v = line.rstrip('\n').split('\t'); d[k] = v
    return d
ROOT = os.path.join(HERE, '..')
def static_corpus():
    files = [os.path.join(ROOT, 'engine', 'interpretation', 'copy', 'zh-CN.csv'), os.path.join(ROOT, 'engine', 'public', 'assets', 'app.js'),
             os.path.join(ROOT, 'engine', 'public', 'index.html'), os.path.join(ROOT, 'engine', 'public', 'stats.html'), os.path.join(ROOT, 'engine', 'public', 'data', 'locations.json')]
    for sub in ('interpretation', 'api', 'server'):
        files += glob.glob(os.path.join(ROOT, 'engine', sub, '**', '*.mjs'), recursive=True)
    return '\n'.join(open(f, encoding='utf-8').read() for f in files if os.path.exists(f))
extra = os.path.join(HERE, 'zh_tw_corpus_api.txt')
corpus = static_corpus() + ('\n' + open(extra, encoding='utf-8').read() if os.path.exists(extra) else '')
OV = overrides(); STP = load('STPhrases.txt'); STC = load('STCharacters.txt')
phrases = {k: v for k, v in STP.items() if k in corpus}
phrases.update({k: v for k, v in OV.items() if len(k) > 1})
chars = {k: v for k, v in STC.items() if k != v}
chars.update({k: v for k, v in OV.items() if len(k) == 1})
chars = {k: v for k, v in chars.items() if k != v}
for k, v in OV.items():
    if len(k) == 1 and k == v: chars.pop(k, None)   # identity override: keep the character as is
tw = [load('TWPhrases.txt'), load('TWVariantsPhrases.txt'), load('TWVariants.txt')]
data = {'source': 'OpenCC s2twp dictionaries (Apache-2.0) + 观辰 overrides; generated by tools/gen_zh_tw.py',
        'p': phrases, 'c': chars, 'tw': tw}
json.dump(data, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
print('phrases', len(phrases), 'chars', len(chars), 'tw', [len(x) for x in tw], 'bytes', os.path.getsize(OUT))
